from __future__ import annotations

import csv
from pathlib import Path

from _common import ROOT, get_claim_decision, get_group_spec, load_json, official_targets

REPORT_MD = ROOT / 'reports/results_summary.md'
REPORT_CSV = ROOT / 'reports/results_summary.csv'


def find_latest_summary(group: str) -> dict | None:
    candidates = sorted(ROOT.glob(f'runs/full/*/{group}/run_summary.json'), key=lambda p: p.stat().st_mtime, reverse=True)
    if not candidates:
        return None
    valid = [path for path in candidates if load_json(path).get('pipeline_status') == 'valid']
    chosen = valid[0] if valid else candidates[0]
    return load_json(chosen)


def pct(x: float | None) -> str:
    if x is None:
        return ''
    return f'{x:.2%}'



def pct_delta(measured: int | None, official: int) -> str:
    if measured is None:
        return ''
    return f'{(measured - official) / official:.2%}'



def main() -> None:
    rows = []
    md_lines = ['# Results Summary', '', '> Auto-generated by `python3 scripts/build_results_summary.py`.', '']
    md_lines.append('| group | claim_class | pipeline_status | completion_rate | official_input_tokens_total | qa_input_tokens_total | visible_pipeline_input_tokens_total | delta_vs_official_qa | delta_vs_official_pipeline | run_id | snapshot_id | notes |')
    md_lines.append('|---|---|---|---:|---:|---:|---:|---:|---:|---|---|---|')

    for target in official_targets()['rows']:
        group = target['group']
        summary = find_latest_summary(group)
        claim = get_claim_decision(group)
        spec = get_group_spec(group)
        if summary is None:
            row = {
                'group': group,
                'claim_class': claim['effective_claim_class'],
                'pipeline_status': 'not_run',
                'completion_rate': '',
                'official_input_tokens_total': target['official_input_tokens_total'],
                'qa_input_tokens_total': '',
                'visible_pipeline_input_tokens_total': '',
                'delta_vs_official_qa': '',
                'delta_vs_official_pipeline': '',
                'run_id': '',
                'snapshot_id': spec.get('openviking_snapshot_id') or 'openclaw-only',
                'notes': claim['decision_basis'],
            }
        else:
            notes = summary.get('notes', []) + summary.get('invalidity_reasons', [])
            row = {
                'group': group,
                'claim_class': summary['claim_class'],
                'pipeline_status': summary['pipeline_status'],
                'completion_rate': pct(summary.get('completion_rate')) if summary.get('completion_rate') is not None else '',
                'official_input_tokens_total': target['official_input_tokens_total'],
                'qa_input_tokens_total': summary.get('qa_input_tokens_total', ''),
                'visible_pipeline_input_tokens_total': summary.get('visible_pipeline_input_tokens_total', ''),
                'delta_vs_official_qa': pct_delta(summary.get('qa_input_tokens_total'), target['official_input_tokens_total']),
                'delta_vs_official_pipeline': pct_delta(summary.get('visible_pipeline_input_tokens_total'), target['official_input_tokens_total']),
                'run_id': summary.get('run_id', ''),
                'snapshot_id': summary.get('snapshot_id', ''),
                'notes': '; '.join(notes),
            }
        rows.append(row)
        md_lines.append('| {group} | {claim_class} | {pipeline_status} | {completion_rate} | {official_input_tokens_total} | {qa_input_tokens_total} | {visible_pipeline_input_tokens_total} | {delta_vs_official_qa} | {delta_vs_official_pipeline} | {run_id} | {snapshot_id} | {notes} |'.format(**row))

    with REPORT_CSV.open('w', encoding='utf-8', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
    REPORT_MD.write_text('\n'.join(md_lines) + '\n', encoding='utf-8')
    print(f'Wrote {REPORT_CSV} and {REPORT_MD}')


if __name__ == '__main__':
    main()
